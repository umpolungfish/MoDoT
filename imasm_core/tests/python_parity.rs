#[test]
fn python_rust_parity() {
    let mut bad = 0usize;
    for &(w, want_v, want_r) in CASES {
        let steps = parse_glyph_word(w);
        let (got_v, _) = tri_ancestral_verdict(&steps);
        let got_r = run_word_register(&steps);
        if got_v != want_v || got_r != want_r {
            bad += 1;
            eprintln!("{w}: verdict {got_v} want {want_v}, reg {got_r} want {want_r}");
        }
    }
    assert_eq!(bad, 0, "{bad} of {} words disagree with the Python kernel", CASES.len());
}
